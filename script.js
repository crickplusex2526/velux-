function money(n) { return "₹" + Number(n).toLocaleString("en-IN"); }
function render(filter="all") {
  let list = filter==="all" ? PRODUCTS : filter==="offers" ? PRODUCTS.filter(p=>p.original>p.price) : PRODUCTS.filter(p=>p.category===filter);
  grid.innerHTML = list.map(p => `
    <article class="card">
      <div class="pic"><img src="${p.image}" alt="${p.name}" loading="lazy"></div>
      <div class="info">
        <div class="code">PRODUCT ${
p.code}</div>
        <div class="name">${p.name}</div>
        <div><span class="old">${money(p.original)}</span><span class="price">${money(p.price)}</span><span class="off">25% OFF</span></div>
        <button class="buy" onclick="openCheckout('${p.code}')">BUY NOW</button>
      </div>
    </article>`).join("");
  count.textContent = `${list.length} products`;
}
